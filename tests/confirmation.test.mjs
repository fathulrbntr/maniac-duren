import assert from "node:assert/strict";
import { confirmAction, requestReason } from "../shared/confirmation.mjs";
import { Node } from "./variant-dom.mjs";

const body = new Node("body");
globalThis.document = { body, createElement: (tag) => new Node(tag) };
const current = () => body.querySelector("dialog");
const message = "Selesaikan penerimaan? <img src=x>";
const refused = confirmAction(message);
assert.equal(current().querySelector("p").textContent, message);
assert.equal(Node.activeElement, current().querySelector("[data-cancel]"));
assert.equal(current().querySelectorAll("img").length, 1);
assert.equal(current().querySelector("img").attrs.src, "/assets/logo.png");
assert.equal(current().attrs.role, "alertdialog");
assert.equal(await confirmAction("Duplikat"), false);
assert.equal(body.querySelectorAll("dialog").length, 1);
await current().querySelector("[data-cancel]").fire("click");
assert.equal(await refused, false);
assert.equal(current(), null);
const escaped = confirmAction("Hapus scan?");
await current().fire("cancel");
assert.equal(await escaped, false);
const accepted = confirmAction("Kirim?");
await current().querySelector("form").fire("submit");
assert.equal(await accepted, true);
const reason = requestReason("Alasan pembatalan");
current().querySelector("textarea").value = "  ";
await current().querySelector("form").fire("submit");
assert(current());
current().querySelector("textarea").value = "  Pesanan salah  ";
await current().querySelector("form").fire("submit");
assert.equal(await reason, "Pesanan salah");
const skipped = requestReason("Alasan pembatalan");
await current().querySelector("[data-cancel]").fire("click");
assert.equal(await skipped, null);

const owner = new EventTarget();
owner.open = true;
document.activeElement = { closest: () => owner };
const nested = confirmAction("Lanjutkan penerimaan?");
owner.open = false;
owner.dispatchEvent(new Event("close"));
assert.equal(await nested, false);
assert.equal(current(), null);
