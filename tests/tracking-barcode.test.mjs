import assert from 'node:assert/strict';
import {randomUUID as id} from 'node:crypto';
import {parseTrackingBarcode,checkTrackedLines,checkReceiptLabels} from '../pos/scale-label.mjs';
import {barcodeProduct} from '../pos/barcode-scanner.mjs';
import {receiptBarcode} from '../pos/receipt-barcode.mjs';
import {createStockDemo,applyStockDemoAction,readStockDemo} from '../pos/stock-demo.mjs';
import {fruitSaleDialog} from '../pos/fruit-sale-dialog.mjs';
import {fixture,day} from './stock-demo-fixture.mjs';
import {Node,makeModal} from './variant-dom.mjs';
const a='92010711260000680001000228',b='92010711260000690001000228';
assert.deepEqual(parseTrackingBarcode(a),{barcode:a,tracking:true,machineId:'01',packedDate:'2026-11-07',sequence:'000068',identity:'9201071126000068',itemCode:'0001',grams:228,kg:.228});
assert.equal(parseTrackingBarcode(b).kg,.228);
assert.equal(parseTrackingBarcode('2100010030320'),null);
for(const bad of [a.slice(0,-1),a+'0',a.replace('071126','311126'),a.replace('071126','290226'),a.slice(0,20)+'000000',a.slice(0,20)+'030001'])assert.throws(()=>parseTrackingBarcode(bad));
assert.equal(parseTrackingBarcode(a.replace('071126','290224')).packedDate,'2024-02-29');
const f=fixture();f.fruit.barcode='0001';f.state.access.stock=true;f.state.access.waste=true;
assert.equal(barcodeProduct(f.state,a).product.id,f.fruit.id);
assert.deepEqual(receiptBarcode(a,f.state.products,f.fruit.id),{barcode:a,kg:.228,pieces:1});
let s=createStockDemo(f.state);
const batch={id:id(),storeId:f.store,supplierId:s.stockDemo.supplierId,date:day,invoiceNo:'BARCODE-101',shippingCost:0,unloadingComplete:true,lines:[{id:id(),productId:f.fruit.id,purchaseCost:10000,weighings:[a,b].map(barcode=>({id:id(),barcode,kg:.228,pieces:1}))}]};
s=applyStockDemoAction(s,'receipt_batch',batch);
assert.equal(s.fruitUnits.length,2);assert.equal(s.fruitEvents.length,2);
assert.equal(applyStockDemoAction(s,'receipt_batch',batch),s);
assert.throws(()=>checkReceiptLabels(s,batch.lines),/sudah tercatat/);
const initial=createStockDemo(f.state);
assert.throws(()=>checkReceiptLabels(initial,[{...batch.lines[0],weighings:[batch.lines[0].weighings[0],batch.lines[0].weighings[0]]}]),/sudah tercatat/);
assert.throws(()=>checkReceiptLabels(initial,[{...batch.lines[0],weighings:[batch.lines[0].weighings[0],{kg:1,pieces:1}]}]),/catatan manual/);
let draft=[];const m=makeModal();
const open=()=>fruitSaleDialog({productId:f.fruit.id,scale:parseTrackingBarcode(a),getState:()=>s,getDraft:()=>draft,store:f.store,modal:m.modal,onAdd:line=>draft.push(line)});
const ui=open(),d=ui.dialog,c=name=>d.querySelector(`[name="${name}"]`);
assert.equal(c('lotId').value,batch.lines[0].id);assert(c('lotId').disabled);assert(c('receiptDate').readOnly);assert.equal(Node.activeElement,c('unit'));
await d.querySelector('form').fire('submit');assert.equal(draft.length,1);assert.equal(draft[0].barcode,a);
assert.throws(open,/sudah ada/);
assert.throws(()=>checkTrackedLines(s,f.store,[draft[0],draft[0]]),/sudah ada/);
assert.throws(()=>checkTrackedLines(s,f.store,[{...draft[0],barcode:undefined}]),/Scan barcode/);
s=applyStockDemoAction(s,'cashier_shift_open',{id:id(),storeId:f.store,openingCash:0});
const sale={id:id(),storeId:f.store,date:day,payment:'Tunai',paid:34200,lines:draft};s=applyStockDemoAction(s,'order_create',sale);
assert.equal(s.fruitUnits.find(u=>u.barcode===a).status,'sold');assert.equal(s.orders.find(o=>o.id===sale.id).lines[0].barcode,a);
assert.throws(()=>applyStockDemoAction(s,'order_create',{...sale,id:id()}),/Terjual/);
const vr={id:id(),storeId:f.store,date:day,kind:'void',orderId:sale.id,reason:'Retur uji',returnStock:true};s=applyStockDemoAction(s,'cashier_approval_request',vr);
s=applyStockDemoAction(s,'order_void',{id:id(),storeId:f.store,date:day,orderId:sale.id,approvalId:vr.id,refundConfirmed:true});assert.equal(s.fruitUnits.find(u=>u.barcode===a).status,'available');
const transfer={id:id(),storeId:f.store,lotId:batch.lines[0].id,toStoreId:f.otherStore,kind:'Transfer',kg:.228,pieces:1,date:day,note:'Uji transfer',barcodes:[b]};
s=applyStockDemoAction(s,'movement',transfer);assert.equal(s.fruitUnits.find(u=>u.barcode===b).storeId,f.otherStore);
assert.equal(readStockDemo(s,'pos_fruit_history',{code:b}).length,2);
assert.equal(f.state.fruitUnits,undefined,'real state isolated');
console.log('PASS 26-digit labels: real scan examples, dates/gram boundaries, exact mapping, receipt dedupe, automatic lot/supplier, immutable quantities, duplicate cart guard, demo sale/refund/transfer and history.');
